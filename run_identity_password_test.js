'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const {criarServicoIdentidade}=require('./functions/identidade_acesso');
const fixture=fs.readFileSync('run_identity_access_test.js','utf8').split('const fixed =')[0];
const {fakeDb,fakeAuth}=vm.runInNewContext(fixture+'\n;({fakeDb,fakeAuth})',{require,console});
const date=new Date('2026-11-03T20:00:00Z');
(async()=>{
  const db=fakeDb({usuarios:{adm:{role:'admin',nome:'Admin'},op:{role:'pd',email:'op@example.test',nome:'Fictício',modulos:{pd:true},tenant_id:'kuryos'},orphan:{role:'qualidade',email:'orphan@example.test',nome:'Órfão',tenant_id:'kuryos'}}});
  const auth=fakeAuth({adm:{uid:'adm',email:'admin@example.test'},op:{uid:'op',email:'op@example.test'}});
  const service=criarServicoIdentidade({db,auth,now:()=>date});
  const call=(data,uid='adm',authTime=date.getTime()/1000)=>service.executar({auth:{uid,token:{auth_time:authTime}},data});
  const pass={acao:'definir_senha',uid:'op',confirmacao_email:'op@example.test',nova_senha:'SenhaFicticia9!'};
  const permission={acao:'funcoes',uid:'orphan',funcoes:['qualidade'],tenant_id:'kuryos',requestId:'permissions_orphan_0001'};
  await assert.rejects(call(permission),e=>e.details.semLogin===true && !e.details.resultadoParcial);
  await assert.rejects(call(pass,'op'),e=>e.code==='permission-denied');
  await assert.rejects(call(pass,'adm',1),e=>e.details.requiresRecentLogin===true);
  await assert.rejects(call({...pass,nova_senha:'curta'}),/8 a 128/);
  await assert.rejects(call({...pass,confirmacao_email:'errado@example.test'}),/Confirme/);
  const before=JSON.stringify(db.state.usuarios.op);
  await call({...pass,requestId:'password_valid_0001'});
  assert.equal(auth.users.op.password,pass.nova_senha);
  assert.equal(JSON.stringify(db.state.usuarios.op),before);
  assert.ok(db.state.security_sessions.op.revokedAfter);
  assert.ok(!JSON.stringify(db.state).includes(pass.nova_senha),'senha nunca persiste no journal/auditoria');
  const changes=auth.calls.filter(c=>c[0]==='updateUser'&&c[2].password).length;
  await call({...pass,requestId:'password_valid_0001'});
  assert.equal(auth.calls.filter(c=>c[0]==='updateUser'&&c[2].password).length,changes);
  await call({...pass,uid:'orphan',confirmacao_email:'orphan@example.test',requestId:'password_orphan_0001'});
  assert.equal(auth.users.orphan.uid,'orphan');
  assert.equal(db.state.usuarios.orphan.role,'qualidade');
  await call(permission);
  db.state.usuarios.duplicate={email:'orphan@example.test',nome:'Histórico',role:'pd'};
  await assert.rejects(call({...pass,uid:'duplicate',confirmacao_email:'orphan@example.test'}),/outro perfil/);
  assert.equal(auth.users.duplicate,undefined);
  const failDb=fakeDb({usuarios:{adm:{role:'admin'},op:{role:'pd',email:'op@example.test'}}});
  const failAuth=fakeAuth({op:{uid:'op',email:'op@example.test',password:'AnteriorFicticia8!'}});
  failAuth.revokeRefreshTokens=async()=>{throw Error('revogação indisponível');};
  const failService=criarServicoIdentidade({db:failDb,auth:failAuth,now:()=>date});
  await assert.rejects(failService.executar({auth:{uid:'adm',token:{auth_time:date.getTime()/1000}},data:pass}),e=>e.details.resultadoParcial===true);
  assert.equal(failAuth.users.op.password,'AnteriorFicticia8!','não muda senha se revogação falhar');
  assert.ok(!JSON.stringify(failDb.state).includes(pass.nova_senha));
  console.log('Senha ADM: acesso recente, autorização, confirmação, política, UID/permissões, segredo ausente e retry idempotente OK');
})().catch(e=>{console.error(e.message);process.exitCode=1;});
