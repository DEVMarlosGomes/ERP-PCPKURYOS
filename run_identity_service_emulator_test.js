'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict'),path=require('node:path');
const req=require('node:module').createRequire(path.resolve('functions/package.json'));
const {initializeApp,deleteApp}=req('firebase-admin/app');
const {getDatabase}=req('firebase-admin/database');
const {criarServicoIdentidade}=require('./functions/identidade_acesso');
if(process.env.FIREBASE_DATABASE_EMULATOR_HOST!=='127.0.0.1:9023')throw Error('Exige emulador RTDB 127.0.0.1:9023');
const fixtures=fs.readFileSync('run_identity_access_test.js','utf8').split('const fixed =')[0];
const {fakeAuth}=vm.runInNewContext(fixtures+'\n;({fakeAuth})',{require,console});
const app=initializeApp({projectId:'demo-identidade',databaseURL:'http://127.0.0.1:9023?ns=demo-identidade-default-rtdb'},'service-emulator');
const db=getDatabase(app),date=new Date('2026-11-03T18:00:00Z');
(async()=>{
  await db.ref().set({usuarios:{adm:{nome:'Synthetic admin',email:'admin@example.test',role:'admin'},op:{nome:'Synthetic operator',email:'operator@example.test',role:'production'},orphan:{nome:'Synthetic orphan',email:'orphan@example.test',role:'qualidade'}}});
  const auth=fakeAuth({adm:{uid:'adm',email:'admin@example.test'},op:{uid:'op',email:'operator@example.test'}});
  const service=criarServicoIdentidade({db,auth,now:()=>date});
  const call=data=>service.executar({auth:{uid:'adm',token:{auth_time:date.getTime()/1000}},data});
  await call({acao:'modulos',uid:'op',modulos:{cadastros:true},requestId:'emulator_modules_0001'});
  assert.equal((await db.ref('usuarios/op/modulos/cadastros').get()).val(),true);
  assert.equal((await db.ref('identidade_locks').get()).exists(),false);
  const payload={acao:'criar',nome:'Synthetic new',email:'new@example.test',funcoes:['production'],requestId:'emulator_concurrent_0001'};
  const results=await Promise.allSettled([call(payload),call(payload)]);
  assert.ok(results.some(r=>r.status==='fulfilled'));
  assert.equal(auth.calls.filter(c=>c[0]==='createUser').length,1);
  assert.equal((await call(payload)).ok,true);
  assert.equal(auth.calls.filter(c=>c[0]==='createUser').length,1);
  await call({acao:'regularizar_login',uid:'orphan',confirmacao_email:'orphan@example.test',requestId:'emulator_regularize_0001'});
  assert.equal(auth.users.orphan.uid,'orphan');
  assert.equal((await db.ref('usuarios/orphan/role').get()).val(),'qualidade');
  auth.revokeRefreshTokens=async()=>{throw Error('synthetic-revoke-failure');};
  await assert.rejects(call({acao:'modulos',uid:'op',modulos:{logistica:true},requestId:'emulator_failure_0001'}),/synthetic-revoke-failure/);
  assert.equal((await db.ref('usuarios/op/modulos/cadastros').get()).val(),true);
  assert.equal((await db.ref('usuarios/op/modulos/logistica').get()).exists(),false);
  const logs=Object.values((await db.ref('auditoria_acessos').get()).val());
  assert.ok(logs.some(l=>l.status==='REQUER_CONFERENCIA'));
  assert.ok(logs.filter(l=>l.status==='CONCLUIDO').length>=3);
  console.log('Serviço identidade no RTDB real emulado: journal, locks/cache frio, compensação, UID preservado e concorrência/idempotência OK');
})().catch(e=>{console.error(e);process.exitCode=1;}).finally(()=>deleteApp(app));
